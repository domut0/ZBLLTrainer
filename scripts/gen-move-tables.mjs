// Emits src/cube/moves.generated.ts.
//
// Issue 05 has to validate an algorithm the user pastes: parse it, apply its
// inverse, and check it produces this case. That needs a cube in the browser —
// but not a solver. The PRD is explicit that no solver ships in the client
// bundle (§7b), and cubing.js is a megabyte-plus with a WASM payload.
//
// So the client gets a ~100-line move applier instead, and the move tables it
// applies are generated here from cubing.js rather than typed out by hand. Same
// principle as scripts/facelets.mjs: the library is the ground truth, and
// src/cube/apply.test.ts checks the two agree on all 977 real algorithms.

import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { cube3x3x3 } from "cubing/puzzles";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const kpuzzle = await cube3x3x3.kpuzzle();
const def = kpuzzle.definition;

// Every quantum move cubing.js knows for a 3x3x3: faces, wide faces, slices and
// whole-cube rotations. Anything a user might paste is one of these, possibly
// with a ' or 2 suffix.
const WANTED = ["U", "R", "F", "D", "L", "B", "u", "r", "f", "d", "l", "b", "M", "E", "S", "x", "y", "z"];

const missing = WANTED.filter((m) => !def.moves[m]);
if (missing.length) throw new Error(`kpuzzle is missing moves: ${missing.join(", ")}`);

const table = {};
for (const name of WANTED) {
  const mv = def.moves[name];
  table[name] = {
    cp: mv.CORNERS.permutation,
    co: mv.CORNERS.orientationDelta,
    ep: mv.EDGES.permutation,
    eo: mv.EDGES.orientationDelta,
  };
}

const body = `// GENERATED by scripts/gen-move-tables.mjs — do not edit.
//
// Permutation and orientation deltas for every quantum move of a 3x3x3, lifted
// straight out of cubing.js's own puzzle definition. Regenerate with:
//
//     node scripts/gen-move-tables.mjs
//
// src/cube/apply.test.ts asserts these stay in step with cubing.js.

export interface MoveTable {
  /** Corner permutation: piece at slot i comes from slot cp[i]. */
  cp: readonly number[]
  /** Corner orientation delta, mod 3. */
  co: readonly number[]
  ep: readonly number[]
  /** Edge orientation delta, mod 2. */
  eo: readonly number[]
}

export const MOVES: Readonly<Record<string, MoveTable>> = ${JSON.stringify(table, null, 2)} as const

export const QUANTUM_MOVES = ${JSON.stringify(WANTED)} as const
`;

writeFileSync(join(ROOT, "src", "cube", "moves.generated.ts"), body);
console.log(`wrote src/cube/moves.generated.ts with ${WANTED.length} quantum moves`);
